/**
 * Generate the per-type reference docs.
 *
 * Hand-written per-type docs drift from the renderer within a release. These
 * are generated from the registry, the guidance map and the starter content, so
 * a doc cannot describe behaviour the code does not have.
 * `scripts/verify-docs-sync.mjs` fails the build if they are stale.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { DIAGRAM_TYPES, createDiagram } from "../src/model.js";
import { getRenderer } from "../src/types/index.js";
import { guidanceFor } from "../src/types/guidance.js";
import { stringify } from "../src/dsl/index.js";
import { toMermaid } from "../src/export/mermaid.js";
import { buildSVG } from "../src/render/svg.js";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const outDir = join(root, "skills", "create-editorial-diagrams", "references");

/** The model fields a type actually uses, derived from its starter content. */
function fieldsUsed(diagram) {
  const nodeFields = new Set();
  for (const node of diagram.nodes) {
    for (const key of Object.keys(node)) {
      if (!["id", "x", "y", "w", "h", "label"].includes(key)) nodeFields.add(key);
    }
  }
  const diagramFields = Object.keys(diagram).filter((key) =>
    ["axes", "lanes", "horizons", "hub", "overlaps", "unit", "timeUnit", "seriesLabel", "groups"].includes(key),
  );
  return { nodeFields: [...nodeFields].sort(), diagramFields: diagramFields.sort() };
}

export function docFor(type) {
  const renderer = getRenderer(type.id);
  const guidance = guidanceFor(type.id);
  const diagram = createDiagram(type.id);
  buildSVG(diagram, { interactive: false, uid: type.id });
  const { nodeFields, diagramFields } = fieldsUsed(diagram);
  const mermaid = toMermaid(diagram);

  const lines = [
    `# ${type.label}`,
    "",
    `> ${type.description}`,
    "",
    `- **Family:** \`${type.family}\``,
    `- **Type id:** \`${type.id}\``,
    `- **Starter size:** ${diagram.width}×${diagram.height} px, ${diagram.nodes.length} nodes, ${diagram.edges.length} connections`,
    ...(renderer.direction ? [`- **Default direction:** ${renderer.direction}`] : []),
    "",
    "## Use it for",
    "",
    guidance?.use ?? "—",
    "",
    "## Do not use it for",
    "",
    guidance?.avoid ?? "—",
    "",
    "## Composition rules",
    "",
    ...(guidance?.compose ?? []).map((rule) => `- ${rule}`),
    "",
    "## The mistake people make",
    "",
    guidance?.mistake ?? "—",
    "",
    "## Model fields this type reads",
    "",
    `Node: ${nodeFields.length ? nodeFields.map((field) => `\`${field}\``).join(", ") : "`label` only"}`,
    "",
    ...(diagramFields.length ? [`Diagram: ${diagramFields.map((field) => `\`${field}\``).join(", ")}`, ""] : []),
    "## Starter content",
    "",
    "```ds",
    stringify(diagram).trimEnd(),
    "```",
    "",
    "## As Mermaid",
    "",
    ...(mermaid.notes.length ? [...mermaid.notes.map((note) => `> ${note}`), ""] : []),
    "```",
    mermaid.text.trimEnd(),
    "```",
    "",
    "## Build one",
    "",
    "```bash",
    `diagram-studio create ${type.id} -o ${type.id}.svg`,
    "```",
    "",
    `Rendered examples: [\`docs/gallery/${type.id}-light.svg\`](../../../docs/gallery/${type.id}-light.svg) · [dark](../../../docs/gallery/${type.id}-dark.svg)`,
    "",
  ];

  return `${lines.join("\n")}`;
}

async function main() {
  await mkdir(outDir, { recursive: true });
  for (const type of DIAGRAM_TYPES) {
    await writeFile(join(outDir, `type-${type.id}.md`), docFor(type), "utf8");
  }

  const index = [
    "# Diagram types",
    "",
    "Choose by the relationship you are showing, not by habit. Each entry links to",
    "the type's own reference, which states when the form is wrong as well as when",
    "it is right.",
    "",
    "| Type | Family | Communication job |",
    "| --- | --- | --- |",
    ...DIAGRAM_TYPES.map((type) => `| [${type.label}](type-${type.id}.md) | \`${type.family}\` | ${type.description} |`),
    "",
    "## Choosing",
    "",
    "- **Structure, not time** — architecture, high-level, nested, layers, network.",
    "- **Time and order** — sequence, process, timeline, roadmap, journey, gantt, deployment.",
    "- **Decisions** — flowchart, state.",
    "- **Ownership** — swimlane, org chart.",
    "- **Hierarchy** — tree, org chart, nested, mind map.",
    "- **Comparison and measurement** — bar, line, scatter, radar, quadrant, matrix, venn, pyramid.",
    "- **Data** — er, data flow, medallion.",
    "",
    "If two forms both fit, pick the one that needs fewer elements to make the point.",
    "",
    "_Generated by `scripts/build-type-docs.mjs` — edit `src/types/guidance.js`, not these files._",
    "",
  ].join("\n");

  await writeFile(join(outDir, "diagram-types.md"), index, "utf8");
  console.log(`wrote ${DIAGRAM_TYPES.length} type references and the index to skills/create-editorial-diagrams/references/`);
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("build-type-docs.mjs")) {
  main();
}
