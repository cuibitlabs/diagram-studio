/**
 * Vendor product marks from simple-icons.
 *
 * The original icon set covers concepts — a database, a queue, a gateway. It
 * cannot draw a Kubernetes logo, and a cloud architecture diagram that has to
 * say "Postgres" in a box instead of showing the mark is doing less work than
 * the reader needs.
 *
 * simple-icons is CC0, so there is no attribution burden, and every glyph is a
 * single solid path at one optical weight — which is why it is the only set
 * vendored here. Mixing four icon libraries gives four visual weights.
 *
 * Run once, commit the result. The build never fetches; `src/render/brand-icons.js`
 * is generated and checked in, and the pinned list below is the manifest.
 */

import { writeFile } from "node:fs/promises";

const SOURCE = "https://raw.githubusercontent.com/simple-icons/simple-icons/master/icons";

/** Pinned list. Grouped by what people actually draw. */
const WANTED = {
  cloud: ["googlecloud", "digitalocean", "cloudflare", "vercel", "netlify"],
  runtime: ["kubernetes", "docker", "terraform", "ansible", "nginx", "apache", "linux"],
  data: ["postgresql", "mysql", "redis", "mongodb", "sqlite", "elasticsearch", "apachekafka", "rabbitmq", "apacheairflow", "apachespark", "apachehive", "snowflake", "databricks", "clickhouse", "duckdb", "googlebigquery"],
  delivery: ["github", "gitlab", "githubactions", "jenkins", "argo"],
  observability: ["grafana", "prometheus", "sentry", "opentelemetry"],
  platform: ["stripe", "auth0", "okta", "keycloak", "firebase", "supabase"],
  language: ["python", "javascript", "typescript", "nodedotjs", "go", "rust", "openjdk", "php", "ruby", "dotnet"],
  framework: ["react", "nextdotjs", "vuedotjs", "svelte", "django", "fastapi", "spring", "graphql", "swagger"],
  work: ["jira", "confluence", "notion", "linear", "figma"],
  analysis: ["looker", "jupyter", "pandas"],
  ai: ["anthropic", "huggingface", "ollama"],
};

/**
 * Marks that are deliberately absent, and why.
 *
 * These were removed from simple-icons at the trademark owner's request. They
 * are not fetched from anywhere else: shipping a mark whose owner has
 * specifically objected to redistribution is not a gap worth closing. Use the
 * concept icons in `icons.js` and name the product in the label — which is what
 * the diagram should be doing anyway.
 */
export const UNAVAILABLE = {
  aws: "cloud",
  azure: "cloud",
  heroku: "cloud",
  slack: "mail",
  tableau: "chart",
  powerbi: "chart",
  dbt: "pipeline",
  openai: "robot",
  twilio: "mail",
  sendgrid: "mail",
  sonarqube: "check",
};

/** Names people will actually type, mapped onto the upstream slug. */
const ALIAS = {
  amazonwebservices: "aws",
  microsoftazure: "azure",
  googlecloud: "gcp",
  nodedotjs: "node",
  nextdotjs: "nextjs",
  vuedotjs: "vue",
  openjdk: "java",
  apachekafka: "kafka",
  apacheairflow: "airflow",
  apachespark: "spark",
  githubactions: "github-actions",
  opentelemetry: "otel",
  huggingface: "hugging-face",
};

const name = (slug) => ALIAS[slug] ?? slug;

async function fetchIcon(slug) {
  const response = await fetch(`${SOURCE}/${slug}.svg`);
  if (!response.ok) return null;
  const svg = await response.text();
  const path = svg.match(/ d="([^"]+)"/)?.[1];
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1] ?? slug;
  return path ? { slug, name: name(slug), title, path } : null;
}

async function main() {
  const found = [];
  const missing = [];

  for (const [group, slugs] of Object.entries(WANTED)) {
    for (const slug of slugs) {
      const icon = await fetchIcon(slug);
      if (icon) found.push({ ...icon, group });
      else missing.push(slug);
    }
  }

  found.sort((a, b) => a.name.localeCompare(b.name));

  const module = `/**
 * Product marks, vendored from simple-icons (CC0-1.0).
 *
 * GENERATED by scripts/build-brand-icons.mjs — do not edit. Re-run that script
 * to refresh, and commit the result: the build never reaches the network.
 *
 * These are solid 24×24 glyphs on a single optical weight, which is why only
 * one upstream set is vendored. The originals in \`icons.js\` cover concepts
 * (a database, a queue, a gateway); these cover named products.
 *
 * The marks are trademarks of their respective owners and are included for
 * nominative use — identifying the product a node represents. See
 * THIRD_PARTY_NOTICES.md.
 *
 * ${found.length} marks.
 */

/** name → { title, group, path } */
export const BRAND_ICONS = {
${found.map((icon) => `  ${JSON.stringify(icon.name)}: { title: ${JSON.stringify(icon.title)}, group: ${JSON.stringify(icon.group)}, path: ${JSON.stringify(icon.path)} },`).join("\n")}
};

export const BRAND_ICON_NAMES = Object.keys(BRAND_ICONS);
export const hasBrandIcon = (name) => Object.hasOwn(BRAND_ICONS, name);

/**
 * Marks that are deliberately absent, mapped to the concept icon to use
 * instead. Removed from the upstream set at the trademark owner's request; a
 * mark whose owner objects to redistribution is not a gap worth closing.
 */
export const UNAVAILABLE_MARKS = ${JSON.stringify(UNAVAILABLE, null, 2).replace(/\n/g, "\n")};

/** Grouped, for a picker. */
export const BRAND_ICON_GROUPS = BRAND_ICON_NAMES.reduce((groups, name) => {
  const group = BRAND_ICONS[name].group;
  (groups[group] ??= []).push(name);
  return groups;
}, {});
`;

  await writeFile(new URL("../src/render/brand-icons.js", import.meta.url), module, "utf8");
  console.log(`wrote ${found.length} product marks to src/render/brand-icons.js`);
  if (missing.length) console.log(`not found upstream (slug changed?): ${missing.join(", ")}`);
}

main();
